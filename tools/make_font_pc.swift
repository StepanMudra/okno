// Bakes fonts/Roboto-Regular.ttf into an 8-bit alpha atlas for the PC version (pc/font_data.h).
// The glyph set is fonts/whitelist.txt, the same one the 3DS font is built from.
// Usage: swift tools/make_font_pc.swift > pc/font_data.h
import CoreText
import Foundation

let root = URL(fileURLWithPath: CommandLine.arguments[0]).deletingLastPathComponent().deletingLastPathComponent()
let px: CGFloat = 40  // em size in the atlas; the game draws it at half size (20 px = the 3DS font)
let data = try! Data(contentsOf: root.appendingPathComponent("fonts/Roboto-Regular.ttf"))
let desc = CTFontManagerCreateFontDescriptorFromData(data as CFData)!
let font = CTFontCreateWithFontDescriptor(desc, px, nil)
let codes = try! String(contentsOf: root.appendingPathComponent("fonts/whitelist.txt"), encoding: .utf8)
    .split(whereSeparator: { $0 == " " || $0 == "\n" }).compactMap { UInt32($0) }

let ascent = CTFontGetAscent(font), descent = CTFontGetDescent(font)
let W = 1024, pad = 2
var H = 0
struct G { var cp: UInt32; var x, y, w, h: Int; var ox, oy, adv: CGFloat }
var glyphs: [(G, CGGlyph)] = []
var cx = pad, cy = pad, rowH = 0
for cp in codes {
    var chars = Array(String(UnicodeScalar(cp)!).utf16)
    var g = CGGlyph(0)
    guard CTFontGetGlyphsForCharacters(font, &chars, &g, chars.count) else { continue }
    var adv = CGSize.zero
    CTFontGetAdvancesForGlyphs(font, .horizontal, &g, &adv, 1)
    var r = CGRect.zero
    CTFontGetBoundingRectsForGlyphs(font, .horizontal, &g, &r, 1)
    let w = Int(ceil(r.width)) + 2, h = Int(ceil(r.height)) + 2
    if cx + w + pad > W { cx = pad; cy += rowH + pad; rowH = 0 }
    // ox: left edge relative to the pen; oy: top edge relative to the top of the line
    glyphs.append((G(cp: cp, x: cx, y: cy, w: w, h: h, ox: floor(r.minX) - 1, oy: ascent - ceil(r.maxY) - 1, adv: adv.width), g))
    cx += w + pad
    rowH = max(rowH, h)
}
H = cy + rowH + pad
var pixels = [UInt8](repeating: 0, count: W * H)
let ctx = CGContext(data: &pixels, width: W, height: H, bitsPerComponent: 8, bytesPerRow: W,
                    space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
ctx.setFillColor(gray: 1, alpha: 1)
ctx.setAllowsAntialiasing(true)
for (gl, g) in glyphs {
    var glyph = g
    // CoreGraphics has its origin bottom-left
    var pos = CGPoint(x: CGFloat(gl.x) - gl.ox, y: CGFloat(H) - CGFloat(gl.y) - ascent + gl.oy)
    CTFontDrawGlyphs(font, &glyph, &pos, 1, ctx)
}

var out = "// Generated by tools/make_font_pc.swift – do not edit.\n#pragma once\n"
out += "#define FONT_ATLAS_W \(W)\n#define FONT_ATLAS_H \(H)\n#define FONT_PX \(Int(px))\n"
out += "#define FONT_ASCENT \(String(format: "%.2f", ascent))f\n#define FONT_LINE \(String(format: "%.2f", ascent + descent + 2))f\n"
out += "typedef struct { unsigned cp; short x, y, w, h; float ox, oy, adv; } PcGlyph;\n"
out += "static const PcGlyph FONT_GLYPHS[] = {\n"
for (g, _) in glyphs {
    out += String(format: "  { %u, %d, %d, %d, %d, %.2ff, %.2ff, %.2ff },\n", g.cp, g.x, g.y, g.w, g.h, g.ox, g.oy, g.adv)
}
out += "};\n#define FONT_GLYPH_COUNT \(glyphs.count)\nstatic const unsigned char FONT_ATLAS[] = {\n"
var line = ""
for (i, p) in pixels.enumerated() {
    line += "\(p),"
    if i % 40 == 39 { out += line + "\n"; line = "" }
}
out += line + "\n};\n"
FileHandle.standardOutput.write(out.data(using: .utf8)!)
